export const getLanguage = () =>
  localStorage.getItem("cloudtrade_language") || "en";
export const t = (key) =>
  messages[getLanguage()]?.[key] ||
  extraMessages[getLanguage()]?.[key] ||
  messages.en[key] ||
  extraMessages.en[key] ||
  key;
export function applyLanguage() {
  const language = getLanguage();
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent =
      messages[language]?.[element.dataset.i18n] ||
      extraMessages[language]?.[element.dataset.i18n] ||
      messages.en[element.dataset.i18n] ||
      extraMessages.en[element.dataset.i18n] ||
      element.textContent;
  });
  document.querySelectorAll(".language-switcher").forEach((select) => {
    select.value = language;
    select.onchange = () => {
      localStorage.setItem("cloudtrade_language", select.value);
      location.reload();
    };
  });
}
